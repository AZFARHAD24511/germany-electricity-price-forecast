from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from .evaluate import dm_test  # noqa: E402

RS, RE = "<!-- RESULTS_START -->", "<!-- RESULTS_END -->"
KS, KE = "<!-- KEY_START -->", "<!-- KEY_END -->"

LABEL = {
    "A_legacy_shift24": "A  legacy rolling (leaky), shift 24",
    "B_gate_shift24": "B  gate-closure, shift 24  [PRIMARY]",
    "C_gate_shift24_wx36": "C  gate-closure, weather +36 h",
    "D_gate_shift0": "D  shift 0  [upper bound, not gate-safe]",
    "E_gate_no_external": "E  price-only (no external data)",
}
NOTE = {
    "A_legacy_shift24": "uses price(t-1): not available at gate closure",
    "B_gate_shift24": "primary, leak-free price features",
    "C_gate_shift24_wx36": "strict availability for observed weather",
    "D_gate_shift0": "upper bound: assumes externals known at gate closure",
    "E_gate_no_external": "tests whether externals add skill",
}
NAVY, ORANGE, GREY, RED, GREEN = "#17324D", "#C45C26", "#9AA5B1", "#B23A48", "#2E7D5B"


