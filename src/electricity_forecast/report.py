def _a(n: int) -> str:
    s = str(int(n))
    return "an" if s[0] == "8" or s in {"11", "18"} or (len(s) == 2 and s[0] == "1" and s[1] == "8") else "a"


def _p(v: float) -> str:
    return "<0.001" if v < 0.001 else f"{v:.3f}"


def results_block(abl: pd.DataFrame | None, roll: pd.DataFrame | None, stamp: str) -> str:
    parts = ["## 5. Results", "", f"_Auto-generated by `scripts/run_ablation.py` / `scripts/run_rolling_eval.py` - last update {stamp} UTC._", ""]

    if abl is not None and len(abl):
        a = abl.set_index("config")
        parts += [
            "### 5.1 Backtest ablation (gate-closure protocol)",
            "",
            f"Expanding-window backtest, {int(abl['n_days'].iloc[0])} test days ({int(abl['n_hours'].iloc[0])} hours) in three windows. "
            "p-values: one-sided Diebold-Mariano test (daily losses, Harvey-Leybourne-Newbold correction) that the model beats the baseline. "
            "This section is refreshed whenever `scripts/run_ablation.py` is run (its three test windows are fixed: Jul-Oct 2026).",
            "",
            "| Setup | MAE | RMSE | rMAE vs SN24 | rMAE vs SN168 | p vs SN24 | Note |",
            "|-------|-----|------|--------------|---------------|-----------|------|",
            f"| SN24 (same hour yesterday) | {abl['mae_sn24'].iloc[0]:.2f} | - | 1.00 | - | - | baseline |",
            f"| SN168 (same hour last week) | {abl['mae_sn168'].iloc[0]:.2f} | - | - | 1.00 | - | baseline |",
        ]
        for k, r in a.iterrows():
            tag = "**" if k.startswith("B_") else ""
            parts.append(
                f"| {tag}{LABEL.get(k, k)}{tag} | {tag}{r['mae_ens']:.2f}{tag} | {r['rmse_ens']:.2f} | {r['rmae_vs_sn24']:.3f} | "
                f"{r['rmae_vs_sn168']:.3f} | {_p(r['p_better_than_sn24'])} | {NOTE.get(k, '')} |"
            )
        parts += ["", "![Ablation](reports/figures/ablation_mae.png)", ""]

        bullets = []
        if {"A_legacy_shift24", "B_gate_shift24"} <= set(a.index):
            leak = a.loc["B_gate_shift24", "mae_ens"] - a.loc["A_legacy_shift24", "mae_ens"]
            bullets.append(f"- **Leak size.** The legacy `shift(1).rolling` features flattered MAE by {leak:.2f} EUR/MWh "
                           f"({100 * leak / a.loc['B_gate_shift24', 'mae_ens']:.1f} %) compared with the gate-closure features.")
        if "B_gate_shift24" in a.index:
            b = a.loc["B_gate_shift24"]
            bullets.append(f"- **Primary result (B).** MAE {b['mae_ens']:.2f} vs SN24 {b['mae_sn24']:.2f}: "
                           f"{100 * (1 - b['rmae_vs_sn24']):.0f} % lower error than seasonal naive 24 h "
                           f"(DM p {_p(b['p_better_than_sn24'])}).")
        if {"B_gate_shift24", "E_gate_no_external"} <= set(a.index):
            ext = a.loc["E_gate_no_external", "mae_ens"] - a.loc["B_gate_shift24", "mae_ens"]
            if ext < 0.3:
                bullets.append(f"- **External data add no measurable skill at a 24 h lag** (price-only MAE "
                               f"{a.loc['E_gate_no_external', 'mae_ens']:.2f} vs {a.loc['B_gate_shift24', 'mae_ens']:.2f}). "
                               "The current model is effectively a price-only model.")
            else:
                bullets.append(f"- External data with a 24 h lag improve MAE by {ext:.2f} EUR/MWh.")
        if {"B_gate_shift24", "D_gate_shift0"} <= set(a.index):
            g = a.loc["B_gate_shift24", "mae_ens"] - a.loc["D_gate_shift0", "mae_ens"]
            bullets.append(f"- **Upper bound (D).** Un-lagged external data would lower MAE by {g:.2f} EUR/MWh "
                           f"({100 * g / a.loc['B_gate_shift24', 'mae_ens']:.0f} %). This is NOT a result: it requires wind/solar/weather "
                           "*forecasts* that were demonstrably published before 12:00 CET on D-1, and the weather archive may contain "
                           "reanalysis rather than forecasts.")
        parts += bullets + [""]

    if roll is not None and len(roll):
        best = roll[["mae_sn24", "mae_sn168"]].min(axis=1)
        dm = dm_test(roll["mae"].values, roll["mae_sn24"].values)
        parts += [
            "### 5.2 Retrospective rolling-origin check (same code as the live job)",
            "",
            f"For each Berlin delivery day {roll['date'].iloc[0]} to {roll['date'].iloc[-1]} the data from that day onward is hidden, "
            "the ensemble is retrained, and a direct 24 h forecast is scored. This is a **replay**, not a live pre-gate record.",
            "",
            "| Days | MAE model | MAE SN24 | MAE SN168 | Days model < SN24 | Days model < better of SN24/SN168 | DM p vs SN24 (daily) |",
            "|------|-----------|----------|-----------|-------------------|-----------------------------------|----------------------|",
            f"| {len(roll)} | **{roll['mae'].mean():.2f}** | {roll['mae_sn24'].mean():.2f} | {roll['mae_sn168'].mean():.2f} | "
            f"{int((roll['mae'] < roll['mae_sn24']).sum())}/{len(roll)} | {int((roll['mae'] < best).sum())}/{len(roll)} | {_p(dm['p_model_better'])} |",
            "",
            "![Rolling check](reports/figures/rolling_eval.png)",
            "",
            "Days on which the model lost to SN24: " + (", ".join(str(x) for x in roll.loc[roll["mae"] >= roll["mae_sn24"], "date"]) or "none") + ". "
            "\"Better of SN24/SN168\" is chosen after seeing the day's outcome and is a deliberately harsh yardstick; the primary comparison is SN24.",
            "",
        ]

    parts += [
        "### 5.3 What is NOT yet established",
        "",
        "- **No valid live record yet.** Earlier daily files were produced by superseded code and named by run date, not delivery date; "
        "they are archived in `outputs/forecasts/legacy/` and excluded. Valid pre-gate days are counted in the live block below.",
        "- Short samples (one season, 89 + 23 days). Regime changes (e.g. gas-price shocks) are not covered.",
        "- Bias correction has not been evaluated separately; the results above are without it.",
        "- Hourly resolution only; the day-ahead market moved to 15-minute products on 1 Oct 2025.",
        "- Point forecasts only (no uncertainty); no economic-value evaluation yet.",
    ]
    return "\n".join(parts)


def key_findings(abl: pd.DataFrame | None, roll: pd.DataFrame | None) -> str:
    out = []
    if abl is not None and len(abl):
        a = abl.set_index("config")
        if "B_gate_shift24" in a.index:
            b = a.loc["B_gate_shift24"]
            s = (f"1. **Gate-safe model beats seasonal naive.** {100 * (1 - b['rmae_vs_sn24']):.0f} % lower MAE than SN24 "
                 f"in {_a(b['n_days'])} {int(b['n_days'])}-day backtest")
            if roll is not None and len(roll):
                s += f" and {100 * (1 - roll['mae'].mean() / roll['mae_sn24'].mean()):.0f} % in {_a(len(roll))} {len(roll)}-day retrospective rolling check"
            out.append(s + " (section 5).")
        if {"A_legacy_shift24", "B_gate_shift24"} <= set(a.index):
            leak = a.loc["B_gate_shift24", "mae_ens"] - a.loc["A_legacy_shift24", "mae_ens"]
            out.append(f"2. **The original rolling features leaked.** Removing the leak costs {leak:.2f} EUR/MWh "
                       f"({100 * leak / a.loc['B_gate_shift24', 'mae_ens']:.1f} % of MAE).")
        if {"B_gate_shift24", "E_gate_no_external", "D_gate_shift0"} <= set(a.index):
            ext = a.loc["E_gate_no_external", "mae_ens"] - a.loc["B_gate_shift24", "mae_ens"]
            g = a.loc["B_gate_shift24", "mae_ens"] - a.loc["D_gate_shift0", "mae_ens"]
            if ext < 0.3:
                out.append("3. **External data add no skill at a 24 h lag** (a price-only model is as good). Un-lagged externals would lower "
                           f"MAE by {g:.1f} EUR/MWh, but only if forecasts available before gate closure can be sourced.")
            else:
                out.append(f"3. External data lagged 24 h improve MAE by {ext:.2f} EUR/MWh; un-lagged they would improve it by {g:.1f}.")
    out.append("4. **No claim about live performance yet.** Valid pre-gate live days are counted in the live block at the end of this file.")
    return "\n".join(out)


def update_results(root: Path) -> None:
    root = Path(root)
    m = root / "reports" / "metrics"
    f = root / "reports" / "figures"
    abl = pd.read_csv(m / "ablation.csv") if (m / "ablation.csv").exists() else None
    roll = pd.read_csv(m / "rolling_eval.csv") if (m / "rolling_eval.csv").exists() else None
    if abl is not None and len(abl):
        plot_ablation(abl, f / "ablation_mae.png")
    if roll is not None and len(roll):
        plot_rolling(roll, f / "rolling_eval.png")
    readme = root / "README.md"
    if not readme.exists():
        return
    stamp = pd.Timestamp.now(tz="UTC").strftime("%Y-%m-%d %H:%M")
    block = results_block(abl, roll, stamp)
    text = readme.read_text(encoding="utf-8")
    if RS in text and RE in text:
        text = text.split(RS)[0] + RS + "\n\n" + block + "\n\n" + RE + text.split(RE)[-1]
    else:
        text = text.rstrip() + "\n\n" + RS + "\n\n" + block + "\n\n" + RE + "\n"
    if KS in text and KE in text:
        text = text.split(KS)[0] + KS + "\n" + key_findings(abl, roll) + "\n" + KE + text.split(KE)[-1]
    readme.write_text(text, encoding="utf-8")
    print("README results block updated")
