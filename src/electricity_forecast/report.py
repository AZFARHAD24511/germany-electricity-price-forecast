def plot_ablation(abl: pd.DataFrame, out: Path) -> None:
    rows = [("Seasonal naive 168 h (SN168)", abl["mae_sn168"].iloc[0], GREY, False),
            ("Seasonal naive 24 h (SN24)", abl["mae_sn24"].iloc[0], GREY, False)]
    for _, r in abl.iterrows():
        k = r["config"]
        color = NAVY if k.startswith("B_") else (RED if k.startswith("D_") else ORANGE)
        rows.append((LABEL.get(k, k), r["mae_ens"], color, k.startswith("D_")))
    fig, ax = plt.subplots(figsize=(10, 4.8))
    y = np.arange(len(rows))[::-1]
    for yi, (lab, v, c, hatch) in zip(y, rows):
        ax.barh(yi, v, color=c, alpha=0.9, hatch="//" if hatch else None, edgecolor="white")
        ax.text(v + 0.5, yi, f"{v:.1f}", va="center", fontsize=9)
    ax.set_yticks(y)
    ax.set_yticklabels([r[0] for r in rows], fontsize=9)
    ax.set_xlabel("MAE (EUR/MWh), lower is better")
    n = int(abl["n_days"].iloc[0])
    ax.set_title(f"Backtest ablation - {n} test days, 3 expanding windows")
    ax.grid(axis="x", alpha=0.3)
    ax.set_xlim(0, max(r[1] for r in rows) * 1.12)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=140, bbox_inches="tight")
    plt.close(fig)


def plot_rolling(roll: pd.DataFrame, out: Path) -> None:
    roll = roll.tail(90).reset_index(drop=True)  # keep the chart readable; the table uses all days
    d = pd.to_datetime(roll["date"])
    diff = roll["mae_sn24"] - roll["mae"]
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(11, 6.4), sharex=True, gridspec_kw={"height_ratios": [2, 1]})
    a1.plot(d, roll["mae"], color=NAVY, marker="o", ms=4, label="Model (ensemble)")
    a1.plot(d, roll["mae_sn24"], color=ORANGE, marker="s", ms=4, label="Seasonal naive 24 h")
    a1.set_ylabel("Daily MAE (EUR/MWh)")
    a1.set_title(f"Retrospective rolling-origin check, {d.min():%d %b} - {d.max():%d %b %Y} "
                 f"({len(roll)} delivery days)")
    a1.legend(frameon=False)
    a1.grid(alpha=0.3)
    a2.bar(d, diff, color=[GREEN if v > 0 else RED for v in diff], width=0.8)
    a2.axhline(0, color="black", lw=0.8)
    a2.set_ylabel("SN24 - model\n(>0: model better)")
    a2.grid(axis="y", alpha=0.3)
    fig.autofmt_xdate()
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=140, bbox_inches="tight")
    plt.close(fig)


